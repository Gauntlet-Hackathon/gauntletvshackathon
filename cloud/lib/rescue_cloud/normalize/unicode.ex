  @doc "Python 3.12's Unicode database version the tables come from."
  def unidata_version, do: @unidata_version

  @doc "Decimal value (0..9) of a Unicode decimal digit (Python `isdecimal`), else nil."
  @spec decimal_value(non_neg_integer()) :: 0..9 | nil
  def decimal_value(cp) when cp in ?0..?9, do: cp - ?0
  def decimal_value(cp) when cp < 0x80, do: nil

  def decimal_value(cp) do
    case find(@decimal, cp) do
      {first, _last} -> rem(cp - first, 10)
      nil -> nil
    end
  end

  @doc "Python `str.isdigit` for one code point."
  @spec digit?(non_neg_integer()) :: boolean()
  def digit?(cp) when cp in ?0..?9, do: true
  def digit?(cp) when cp < 0x80, do: false
  def digit?(cp), do: find(@digit, cp) != nil

  @doc "Python `str.isspace` for one code point."
  @spec space?(non_neg_integer()) :: boolean()
  def space?(cp), do: find(@space, cp) != nil

  @doc "Python `unicodedata.combining(c) != 0` for one code point."
  @spec combining?(non_neg_integer()) :: boolean()
  def combining?(cp) when cp < 0x300, do: false
  def combining?(cp), do: find(@combining, cp) != nil

  defp find(ranges, cp), do: search(ranges, cp, 0, tuple_size(ranges) - 1)

  defp search(_ranges, _cp, lo, hi) when lo > hi, do: nil

  defp search(ranges, cp, lo, hi) do
    mid = div(lo + hi, 2)
    {first, last} = range = elem(ranges, mid)

    cond do
      cp < first -> search(ranges, cp, lo, mid - 1)
      cp > last -> search(ranges, cp, mid + 1, hi)
      true -> range
    end
  end
